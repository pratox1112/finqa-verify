"""FinanceBench public sample (150 questions; CC-BY-NC-4.0, PatronusAI).

Downloaded once to data/financebench/ (gitignored) and read from there afterwards.

Audit (ROADMAP P1.1): one row per question in data/financebench_audit.csv, plus the scope
decision and counts in data/SCOPE.md. Both are generated; rerun to refresh them:

    uv run python -m finqa.ingestion.financebench
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import httpx

from finqa.config import CONFIGS_DIR
from finqa.verifiers.numbers import extract_numbers, gold_value

URL = (
    "https://huggingface.co/datasets/PatronusAI/financebench/resolve/main/financebench_merged.jsonl"
)
DATA_DIR = CONFIGS_DIR.parent / "data"
DEFAULT_PATH = DATA_DIR / "financebench" / "financebench_merged.jsonl"
AUDIT_PATH = DATA_DIR / "financebench_audit.csv"
SCOPE_PATH = DATA_DIR / "SCOPE.md"

# Scope decision, 2026-10-30 (docs/DECISIONS.md): only questions on 10-K and 10-Q filings.
IN_SCOPE_DOC_TYPES = frozenset({"10k", "10q"})
DOC_TYPE_NAMES = {"10k": "10-K", "10q": "10-Q", "8k": "8-K", "Earnings": "earnings release"}

AUDIT_COLUMNS = [
    "financebench_id",
    "company",
    "doc_name",
    "doc_type",
    "doc_period",
    "question_type",
    "question_reasoning",
    "answer",
    "answer_kind",
    "gold_value",
    "gold_unit",
    "answer_numbers",
    "in_scope",
    "exclusion_reason",
]


def download(path: Path = DEFAULT_PATH, url: str = URL) -> Path:
    """Fetch the sample unless it is already on disk (cache-first)."""
    if path.exists():
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    response = httpx.get(url, follow_redirects=True, timeout=60)
    response.raise_for_status()
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(response.content)
    tmp.replace(path)
    return path


def load(path: Path = DEFAULT_PATH) -> list[dict[str, Any]]:
    """All records, as published (keys include financebench_id, company, doc_name,
    question_type, question, answer, evidence, doc_type, doc_period)."""
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def by_id(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    return {r["financebench_id"]: r for r in records}


def in_scope(record: dict[str, Any]) -> bool:
    return record["doc_type"] in IN_SCOPE_DOC_TYPES


def gold_columns(question: str, answer: str) -> dict[str, Any]:
    """Gold value for single-number answers (ROADMAP P1.2); every number for the rest.

    answer_kind: "number" (the answer is one number), "text_with_numbers" or "text".
    gold_unit is empty when neither answer nor question states a unit (flagged, not dropped).
    """
    gold = gold_value(question, answer)
    numbers = extract_numbers(answer)
    if gold is not None:
        kind = "number"
    elif numbers:
        kind = "text_with_numbers"
    else:
        kind = "text"
    return {
        "answer_kind": kind,
        "gold_value": "" if gold is None else repr(gold.value),
        "gold_unit": "" if gold is None or gold.unit is None else gold.unit,
        "answer_numbers": "; ".join(f"{n.value!r} {n.unit or '?'}" for n in numbers),
    }


def audit_rows(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = []
    for r in sorted(records, key=lambda r: r["financebench_id"]):
        keep = in_scope(r)
        rows.append(
            {
                "financebench_id": r["financebench_id"],
                "company": r["company"],
                "doc_name": r["doc_name"],
                "doc_type": r["doc_type"],
                "doc_period": r["doc_period"],
                "question_type": r["question_type"],
                "question_reasoning": r.get("question_reasoning") or "",
                "answer": r["answer"],
                **gold_columns(r["question"], r["answer"]),
                "in_scope": keep,
                "exclusion_reason": ""
                if keep
                else f"document type {DOC_TYPE_NAMES.get(r['doc_type'], r['doc_type'])}",
            }
        )
    return rows


def write_audit(rows: list[dict[str, Any]], path: Path = AUDIT_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=AUDIT_COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def scope_report(rows: list[dict[str, Any]]) -> str:
    kept = [r for r in rows if r["in_scope"]]
    dropped = [r for r in rows if not r["in_scope"]]
    companies = {r["company"] for r in rows}
    kept_companies = {r["company"] for r in kept}
    by_doc = Counter(r["doc_type"] for r in rows)
    by_type_kept = Counter(r["question_type"] for r in kept)
    lines = [
        "# Scope",
        "",
        "Generated by `uv run python -m finqa.ingestion.financebench` from the FinanceBench "
        "public sample; do not edit the counts by hand.",
        "",
        "## Decision",
        "",
        "2026-10-30, Pratosh Karthikeyan (`docs/DECISIONS.md`): **only questions on 10-K and "
        "10-Q filings are in scope.** Questions on 8-Ks and earnings releases are excluded: "
        "those documents have no standard item structure or XBRL facts, so they would need "
        "separate parsing and the grounded verifier could not check them.",
        "",
        "## Counts",
        "",
        "| | Questions | Companies |",
        "|---|---|---|",
        f"| FinanceBench public sample | {len(rows)} | {len(companies)} |",
        f"| **In scope** | **{len(kept)}** | **{len(kept_companies)}** |",
        f"| Excluded | {len(dropped)} | {len(companies - kept_companies)} |",
        "",
        "Questions by document type:",
        "",
        "| Document type | Questions | In scope |",
        "|---|---|---|",
    ]
    for doc_type, n in by_doc.most_common():
        name = DOC_TYPE_NAMES.get(doc_type, doc_type)
        lines.append(f"| {name} | {n} | {'yes' if doc_type in IN_SCOPE_DOC_TYPES else 'no'} |")
    lines += [
        "",
        "In-scope questions by question type:",
        "",
        "| Question type | Questions |",
        "|---|---|",
    ]
    lines += [f"| {t} | {n} |" for t, n in sorted(by_type_kept.items())]
    lines += [
        "",
        "In-scope gold answers by kind (`answer_kind` in the audit):",
        "",
        "| Answer kind | Questions |",
        "|---|---|",
        f"| a single number (`gold_value` set) | "
        f"{sum(r['answer_kind'] == 'number' for r in kept)} |",
        "| text containing numbers | "
        f"{sum(r['answer_kind'] == 'text_with_numbers' for r in kept)} |",
        f"| text only | {sum(r['answer_kind'] == 'text' for r in kept)} |",
        "",
        "Single-number answers with no unit in the answer or the question (flagged, not "
        "dropped): "
        + (
            ", ".join(
                f"`{r['financebench_id']}`"
                for r in kept
                if r["answer_kind"] == "number" and not r["gold_unit"]
            )
            or "none"
        )
        + ".",
        "",
        "## Companies with no in-scope questions",
        "",
    ]
    lines += [f"- {c}" for c in sorted(companies - kept_companies)] or ["None."]
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = audit_rows(load(download()))
    write_audit(rows)
    SCOPE_PATH.write_text(scope_report(rows), encoding="utf-8")
    kept = sum(r["in_scope"] for r in rows)
    print(f"{len(rows)} questions, {kept} in scope -> {AUDIT_PATH.name}, {SCOPE_PATH.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
