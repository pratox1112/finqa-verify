"""Planted-error suite with the model (ROADMAP P4.7): V1 and V2 on every hand-made case.

    uv run python scripts/planted_errors.py          # needs the model (inside serve_and_run)

For each case in tests/planted/cases.py, runs V1 (configs/grid/r0_v1.yaml) and V2
(configs/grid/r0_v2.yaml) on the draft and records, per verifier:
  caught   the planted claim is flagged in the first check (V1: marked unsupported;
           V2: a check failed). For a control, any flag is a false alarm.
  after    what the claim became: "fixed" (changed, and its value is within tolerance of the
           true value), "changed, still wrong", or "kept" (unchanged).
and writes docs/PLANTED_ERRORS.md. Model calls go through finqa.llm (cached), so a rerun
replays. The cases are synthetic; no FinanceBench question is involved.
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

from planted.cases import CASES, NWD, QUESTIONS, Case, lookup  # noqa: E402

from finqa.config import CONFIGS_DIR, Config, load_config  # noqa: E402
from finqa.eval.scoring import within_tolerance  # noqa: E402
from finqa.llm import LLM  # noqa: E402
from finqa.schemas import VerifiedResult  # noqa: E402
from finqa.verifiers.grounded import GroundedVerifier  # noqa: E402
from finqa.verifiers.self_check import SelfCheckVerifier  # noqa: E402

OUT = ROOT / "docs" / "PLANTED_ERRORS.md"


def first_round_flags(r: VerifiedResult) -> set[str]:
    return {v.claim_id for v in r.verdicts if v.ok is False and v.reason.startswith("round 1:")}


def after(case: Case, r: VerifiedResult, tolerance: float) -> str:
    if case.planted is None or case.truth is None:
        return "kept" if r.claims_after == r.claims_before else "changed"
    i = [c.claim_id for c in r.claims_before].index(case.planted)
    before, now = r.claims_before[i], r.claims_after[i]
    if now == before:
        return "kept"
    return "fixed" if within_tolerance(now.value, case.truth, tolerance) else "changed, still wrong"


def row(case: Case, r: VerifiedResult, tolerance: float) -> tuple[bool, str]:
    flags = first_round_flags(r)
    caught = case.planted in flags if case.planted else bool(flags)
    return caught, "error: " + r.error if r.error else after(case, r, tolerance)


def summary(name: str, results: dict[str, tuple[bool, str]]) -> list[str]:
    planted = [c for c in CASES if c.planted]
    checkable = [c for c in planted if c.caught_by]
    controls = [c for c in CASES if not c.planted]

    def count(cases: list[Case], what: Callable[[tuple[bool, str]], bool]) -> str:
        return f"{sum(what(results[c.case_id]) for c in cases)}/{len(cases)}"

    return [
        f"| {name} | {count(planted, lambda x: x[0])} | {count(checkable, lambda x: x[0])} "
        f"| {count(planted, lambda x: x[1] == 'fixed')} | {count(controls, lambda x: x[0])} |"
    ]


def markdown(v1: dict[str, tuple[bool, str]], v2: dict[str, tuple[bool, str]], cfg: Config) -> str:
    lines = [
        "# Planted errors: what V1 and V2 catch\n",
        "Generated by `uv run python scripts/planted_errors.py`; do not edit by hand. "
        f"Model `{cfg.model.id}`, thinking `{cfg.model.thinking}`, temperature "
        f"{cfg.model.temperature}; `max_revisions` {cfg.verification.max_revisions}, tolerance "
        f"{cfg.verification.tolerance}. The {len(CASES)} cases are hand-made and synthetic "
        "(fictional companies; `tests/planted/cases.py`): each planted case has one error in "
        "one claim, and each control has none. *Caught* means the planted claim was flagged by "
        "the first check (V1: marked unsupported; V2: a rule-based check failed); for a "
        "control, any flag is a false alarm. *After* is what the claim became after the "
        "revisions. V2's checks are also tested without the model in `tests/test_planted.py`; "
        "*checkable* cases are those V2's checks are designed to catch.\n",
        "## Summary\n",
        "| Verifier | Planted errors caught | Checkable errors caught | Fixed after revision "
        "| False alarms on controls |",
        "|---|---|---|---|---|",
        *summary("V1 self-check", v1),
        *summary("V2 grounded", v2),
        "",
        "## Per case\n",
        "| Case | Error type | V2 checks expected to fail | V1 caught | V1 after "
        "| V2 caught | V2 after | Note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in CASES:
        kind = c.error_type.value if c.error_type else "control"
        expected = ", ".join(sorted(c.caught_by)) or "none"
        (c1, a1), (c2, a2) = v1[c.case_id], v2[c.case_id]
        yes = {True: "yes", False: "no"}
        lines.append(
            f"| `{c.case_id}` | {kind} | {expected} | {yes[c1]} | {a1} | {yes[c2]} | {a2} "
            f"| {c.note} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    v1_cfg = load_config(CONFIGS_DIR / "grid" / "r0_v1.yaml")
    v2_cfg = load_config(CONFIGS_DIR / "grid" / "r0_v2.yaml")
    v1 = SelfCheckVerifier(v1_cfg, LLM(v1_cfg), questions=QUESTIONS)
    v2 = GroundedVerifier(
        v2_cfg, LLM(v2_cfg), context=lambda qid: (QUESTIONS[qid], NWD), lookup=lookup
    )
    out1, out2 = {}, {}
    for c in CASES:
        d = c.draft()
        out1[c.case_id] = row(c, v1(d, v1_cfg), v1_cfg.verification.tolerance)
        out2[c.case_id] = row(c, v2(d, v2_cfg), v2_cfg.verification.tolerance)
        print(f"{c.case_id}: V1 {out1[c.case_id]}, V2 {out2[c.case_id]}")
    OUT.write_bytes(markdown(out1, out2, v2_cfg).encode("utf-8"))
    print(f"-> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
