"""Dev check of the verifiers on one run: V0 vs V1 vs V2, scored against gold, with flips.

    uv run python scripts/compare_verified.py --run <dev run_id>

Reads runs/<run>/drafts.jsonl (V0) and whichever of verified_self_check.jsonl (V1) and
verified_grounded.jsonl (V2) exist, scores each against FinanceBench gold exactly like the
reports (finqa.eval.tables.score_run; text answers through the judge, cached), and writes
runs/<run>/verification_dev.md: accuracy per arm, flips against V0 (wrong -> right and right
-> wrong), questions revised and flagged, failed verifications, and a per-question table.
Dev only: verifier verdicts never decide correctness, gold does (ROADMAP rule 10).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

from finqa.config import BASE_CONFIG, Config, load_config
from finqa.eval import tables
from finqa.eval.questions import load_questions
from finqa.eval.report import default_judge
from finqa.eval.runner import RUNS_DIR, RunRefused, read_jsonl
from finqa.eval.scoring import load_gold
from finqa.schemas import Draft, VerifiedResult

ARMS = {"V1": "self_check", "V2": "grounded"}


def summary_rows(
    v0: Sequence[tables.Row],
    arms: dict[str, tuple[list[tables.Row], list[VerifiedResult]]],
) -> list[str]:
    base = {r.question_id: r.outcome == "correct" for r in v0}
    lines = [
        "| Arm | Correct | Wrong → right | Right → wrong | Revised | Flagged | Failed |",
        "|---|---|---|---|---|---|---|",
        f"| V0 | {sum(base.values())}/{len(base)} | | | | | |",
    ]
    for label, (rows, results) in arms.items():
        now = {r.question_id: r.outcome == "correct" for r in rows}
        up = sum(now[q] and not base[q] for q in now)
        down = sum(base[q] and not now[q] for q in now)
        revised = sum(r.claims_after != r.claims_before for r in results)
        flagged = sum(bool(r.flagged_claim_ids) for r in results)
        failed = sum(r.error is not None for r in results)
        lines.append(
            f"| {label} | {sum(now.values())}/{len(now)} | {up} | {down} | {revised} "
            f"| {flagged} | {failed} |"
        )
    return lines


def per_question(
    v0: Sequence[tables.Row],
    arms: dict[str, tuple[list[tables.Row], list[VerifiedResult]]],
) -> list[str]:
    labels = list(arms)
    lines = [
        "| Question | V0 | " + " | ".join(f"{a} | {a} revisions, flagged" for a in labels) + " |",
        "|---|---|" + "---|---|" * len(labels),
    ]
    outcome = {label: {r.question_id: r.outcome for r in rows} for label, (rows, _) in arms.items()}
    results = {label: {r.question_id: r for r in res} for label, (_, res) in arms.items()}
    for row in v0:
        q = row.question_id
        cells = [f"`{q}`", row.outcome]
        for label in labels:
            r = results[label].get(q)
            detail = (
                "—"
                if r is None
                else f"{r.revisions_used}, {', '.join(r.flagged_claim_ids) or 'none'}"
            )
            if r is not None and r.error:
                detail = f"error: {r.error[:60]}"
            cells += [outcome[label].get(q, "—"), detail]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def compare_verified(run_id: str, runs_dir: Path = RUNS_DIR) -> int:
    run_dir = runs_dir / run_id
    meta = json.loads((run_dir / "run_meta.json").read_text(encoding="utf-8"))
    if meta["split"] != "dev":
        raise RunRefused("the verifier dev check is dev only")
    questions = {q.question_id: q for q in load_questions("dev")}
    gold = load_gold()
    cfg = Config.model_validate(meta["config"])
    judge = default_judge(load_config(BASE_CONFIG, BASE_CONFIG), run_id)
    drafts = read_jsonl(run_dir / "drafts.jsonl", Draft)
    tol = cfg.verification.tolerance
    v0 = tables.score_run(drafts, questions, gold, tol, judge)
    arms: dict[str, tuple[list[tables.Row], list[VerifiedResult]]] = {}
    for label, arm in ARMS.items():
        path = run_dir / f"verified_{arm}.jsonl"
        if path.exists():
            results = read_jsonl(path, VerifiedResult)
            arms[label] = (tables.score_run(drafts, questions, gold, tol, judge, results), results)
    text = "\n".join(
        [
            f"# Verifiers on dev run `{run_id}`\n",
            "Generated by `scripts/compare_verified.py`; scored against FinanceBench gold. "
            "Revised: the verifier changed at least one claim. Flagged: claims still failing "
            "after the revisions.\n",
            *summary_rows(v0, arms),
            "",
            *per_question(v0, arms),
        ]
    )
    out = run_dir / "verification_dev.md"
    out.write_bytes((text + "\n").encode("utf-8"))
    print(text)
    print(f"-> {out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", required=True, help="dev run ID under runs/")
    args = parser.parse_args()
    try:
        return compare_verified(args.run)
    except RunRefused as e:
        print(f"refused: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
